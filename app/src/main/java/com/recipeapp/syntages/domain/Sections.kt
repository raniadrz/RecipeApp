    fun guess(name: String): String {
        val n = Text.normalize(name)
        if (n.isBlank()) return OTHER
        if (n == "πιπερι" || n.startsWith("πιπερι ") || n.startsWith("μαυρο πιπερι")) return SPICES
        if (n.contains("φυλλο κρουστ")) return BAKERY
        if (n.contains("μοσχοκαρυδ") || n.contains("μουσκοκαρυδ")) return SPICES
        for ((section, keys) in rules) {
            if (keys.any { n.contains(it) }) return section
        }
        return OTHER
    }
